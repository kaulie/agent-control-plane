/**
 * Small SQL dialect helpers shared by the Postgres driver and tests.
 * The store still writes `?` placeholders (SQLite style). Postgres wants `$1`.
 */

export interface SqlRunResult {
  changes: number | bigint;
  lastInsertRowid: number | bigint;
}

export interface SqlStatement {
  all(...params: unknown[]): unknown[];
  get(...params: unknown[]): unknown;
  run(...params: unknown[]): SqlRunResult;
}

export interface SqlDatabase {
  exec(sql: string): void;
  prepare(sql: string): SqlStatement;
  close(): void;
}

/** Rewrite `?` placeholders to `$1`, `$2`, … without touching strings or comments. */
export function toPostgresPlaceholders(sql: string): string {
  let out = "";
  let n = 0;
  let i = 0;
  while (i < sql.length) {
    const c = sql[i];
    if (c === "'") {
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === "'") {
          if (sql[j + 1] === "'") {
            j += 2;
            continue;
          }
          j += 1;
          break;
        }
        j += 1;
      }
      out += sql.slice(i, j);
      i = j;
      continue;
    }
    if (c === '"') {
      let j = i + 1;
      while (j < sql.length) {
        if (sql[j] === '"') {
          if (sql[j + 1] === '"') {
            j += 2;
            continue;
          }
          j += 1;
          break;
        }
        j += 1;
      }
      out += sql.slice(i, j);
      i = j;
      continue;
    }
    if (c === "-" && sql[i + 1] === "-") {
      const nl = sql.indexOf("\n", i);
      const j = nl === -1 ? sql.length : nl + 1;
      out += sql.slice(i, j);
      i = j;
      continue;
    }
    if (c === "/" && sql[i + 1] === "*") {
      const end = sql.indexOf("*/", i + 2);
      const j = end === -1 ? sql.length : end + 2;
      out += sql.slice(i, j);
      i = j;
      continue;
    }
    if (c === "?") {
      n += 1;
      out += `$${n}`;
      i += 1;
      continue;
    }
    out += c;
    i += 1;
  }
  return out;
}

/**
 * SQLite DDL the migrator already emits, retargeted at Postgres.
 * `REAL` in SQLite is an 8-byte float; Postgres `REAL` is 4-byte.
 */
export function adaptPostgresDdl(sql: string): string {
  return sql
    .replaceAll(
      /\bINTEGER PRIMARY KEY AUTOINCREMENT\b/g,
      "BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY",
    )
    .replaceAll(/\bREAL\b/g, "DOUBLE PRECISION");
}

export function isUniqueEventIdError(err: unknown): boolean {
  if (!(err instanceof Error)) return false;
  const message = err.message;
  if (/UNIQUE constraint failed: events\.event_id/i.test(message)) return true;
  if (/events_event_id_key/i.test(message)) return true;
  return /duplicate key/i.test(message) && /event_id/i.test(message);
}

/** `host:port/db` for logs. Never includes the user or password. */
export function describeDatabaseUrl(url: string): string {
  try {
    const parsed = new URL(url);
    const db = parsed.pathname.replace(/^\//, "") || "?";
    const port = parsed.port || "5432";
    return `${parsed.hostname}:${port}/${db}`;
  } catch {
    return "configured";
  }
}
