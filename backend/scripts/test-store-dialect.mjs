/**
 * SQL dialect helpers, plus the SQLite store still assigning event seq and
 * upserting concurrency samples / billing rules after the Postgres port.
 *
 * Usage: npx tsx scripts/test-store-dialect.mjs
 */
import assert from "node:assert/strict";
import fs from "node:fs";
import os from "node:os";
import path from "node:path";
import { Store } from "../src/store/db.ts";
import {
  adaptPostgresDdl,
  describeDatabaseUrl,
  isUniqueEventIdError,
  toPostgresPlaceholders,
} from "../src/store/sql-dialect.ts";

delete process.env.DATABASE_URL;
delete process.env.WEB_CURSOR_SQLITE_CUTOVER;

assert.equal(
  toPostgresPlaceholders("SELECT * FROM t WHERE a = ? AND note = '?' AND c = ?"),
  "SELECT * FROM t WHERE a = $1 AND note = '?' AND c = $2",
);
assert.equal(
  toPostgresPlaceholders("SELECT * FROM t WHERE a = ? -- ?\n AND b = ?"),
  "SELECT * FROM t WHERE a = $1 -- ?\n AND b = $2",
);
assert.equal(
  toPostgresPlaceholders("SELECT * FROM t WHERE a = ? AND b = 'it''s ?' AND c = ?"),
  "SELECT * FROM t WHERE a = $1 AND b = 'it''s ?' AND c = $2",
);

const ddl = adaptPostgresDdl(
  "seq INTEGER PRIMARY KEY AUTOINCREMENT, price REAL NOT NULL",
);
assert.match(ddl, /BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY/);
assert.match(ddl, /DOUBLE PRECISION/);
assert.equal(
  adaptPostgresDdl("id INTEGER PRIMARY KEY CHECK (id = 1)"),
  "id INTEGER PRIMARY KEY CHECK (id = 1)",
);

assert.equal(
  isUniqueEventIdError(
    new Error('duplicate key value violates unique constraint "events_event_id_key"'),
  ),
  true,
);
assert.equal(
  isUniqueEventIdError(new Error("UNIQUE constraint failed: events.event_id")),
  true,
);
assert.equal(isUniqueEventIdError(new Error("nope")), false);

const described = describeDatabaseUrl(
  "postgres://web_cursor:s3cret@49.234.45.173:5432/web_cursor?sslmode=require",
);
assert.equal(described, "49.234.45.173:5432/web_cursor");
assert.equal(described.includes("s3cret"), false);

const tmp = fs.mkdtempSync(path.join(os.tmpdir(), "wc-dialect-"));
const store = new Store(tmp);
const seeded = store.listBillingRules().length;
assert.ok(seeded > 0, "billing rules are seeded");
store.insertConcurrencySample("2026-10-16T00:00:00.000Z", 1);
store.insertConcurrencySample("2026-10-16T00:00:00.000Z", 4);
const samples = store.listConcurrencySamplesSince("2026-10-16T00:00:00.000Z");
assert.equal(samples.length, 1);
assert.equal(samples[0].runningCount, 4);
store.close();

const again = new Store(tmp);
assert.equal(again.listBillingRules().length, seeded, "second boot does not duplicate rules");
again.close();
fs.rmSync(tmp, { recursive: true, force: true });

console.log("PASS: store dialect + sqlite upsert");
